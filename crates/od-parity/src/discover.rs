//! Test discovery by reading the workspace's Rust sources.
//!
//! Why source parsing and not `cargo test --workspace -- --list`: the list
//! needs a full build of every test binary (Slint, Rubber Band, ONNX…), it
//! cannot run from inside `cargo test` without fighting over the build lock,
//! and it prints test names without the package they belong to (the binary
//! name only goes to stderr). Parsing the sources is fast, needs no build,
//! and yields ids that are stable across platforms.
//!
//! Test id format (matches what `cargo test --list` prints, prefixed with
//! the package name):
//!
//! - unit tests in a library or binary: `<package>::<module path>::<fn>`,
//!   e.g. `od-engine::mixer::tests::crossfader_curves`
//! - integration tests `tests/<name>.rs` (or `tests/<name>/main.rs`):
//!   `<package>::<name>::<module path>::<fn>`, e.g.
//!   `od-engine::render::echo_repeats_on_beat`
//!
//! The module path comes from the file location (`src/a/b.rs` → `a::b`,
//! `src/a/mod.rs` → `a`) plus inline `mod x { … }` blocks. A test is any
//! `fn` preceded by `#[test]` or an attribute whose path ends in `::test`
//! (`#[tokio::test]`). Limits: tests generated by macros and modules moved
//! with `#[path]` are not seen (none exist today; `parity list-tests`
//! shows what is found).

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

/// One discovered test function.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TestFn {
    pub id: String,
    pub file: PathBuf,
    pub line: usize,
    /// Marked `#[ignore]`: exists but does not run by default.
    pub ignored: bool,
}

/// All tests in the workspace, keyed by id.
#[derive(Debug, Default)]
pub struct TestIndex {
    pub tests: BTreeMap<String, TestFn>,
    /// Ids found more than once (ambiguous references).
    pub duplicates: Vec<String>,
}

impl TestIndex {
    pub fn get(&self, id: &str) -> Option<&TestFn> {
        self.tests.get(id)
    }
    pub fn len(&self) -> usize {
        self.tests.len()
    }
    pub fn is_empty(&self) -> bool {
        self.tests.is_empty()
    }
}

/// Scan `crates/*` and `apps/*` below the workspace root.
pub fn discover(root: &Path) -> std::io::Result<TestIndex> {
    let mut index = TestIndex::default();
    for group in ["crates", "apps"] {
        let dir = root.join(group);
        if !dir.is_dir() {
            continue;
        }
        let mut packages: Vec<PathBuf> = fs::read_dir(&dir)?
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.join("Cargo.toml").is_file())
            .collect();
        packages.sort();
        for pkg_dir in packages {
            let Some(name) = package_name(&pkg_dir.join("Cargo.toml")) else {
                continue;
            };
            scan_package(root, &pkg_dir, &name, &mut index)?;
        }
    }
    Ok(index)
}

fn package_name(manifest: &Path) -> Option<String> {
    let text = fs::read_to_string(manifest).ok()?;
    let value: toml::Table = text.parse().ok()?;
    value
        .get("package")?
        .get("name")?
        .as_str()
        .map(str::to_owned)
}

fn scan_package(
    root: &Path,
    pkg_dir: &Path,
    pkg: &str,
    index: &mut TestIndex,
) -> std::io::Result<()> {
    // Library and binary sources: module path from the file location.
    let src = pkg_dir.join("src");
    for file in rust_files(&src)? {
        let rel = file.strip_prefix(&src).unwrap_or(&file);
        let mut segments = module_segments(rel);
        // src/bin/<name>.rs is its own crate root.
        if segments.first().map(String::as_str) == Some("bin") {
            segments.remove(0);
            if !segments.is_empty() {
                segments.remove(0);
            }
        }
        scan_file(root, &file, pkg, &segments, index)?;
    }
    // Integration tests: tests/<name>.rs and tests/<name>/**.rs.
    let tests = pkg_dir.join("tests");
    for file in rust_files(&tests)? {
        let rel = file.strip_prefix(&tests).unwrap_or(&file);
        let mut segments = module_segments(rel);
        // tests/<name>/main.rs → binary <name>; module_segments already
        // dropped "main".
        if segments.is_empty() {
            continue;
        }
        // For tests/<name>.rs the first segment is the binary name.
        let binary = segments.remove(0);
        let mut prefix = vec![binary];
        prefix.extend(segments);
        scan_file(root, &file, pkg, &prefix, index)?;
    }
    Ok(())
}

fn rust_files(dir: &Path) -> std::io::Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    if !dir.is_dir() {
        return Ok(out);
    }
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        for entry in fs::read_dir(&d)? {
            let path = entry?.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|e| e == "rs") {
                out.push(path);
            }
        }
    }
    out.sort();
    Ok(out)
}

/// `a/b.rs` → [a, b]; `a/mod.rs` → [a]; `lib.rs`, `main.rs` → [].
fn module_segments(rel: &Path) -> Vec<String> {
    let mut segs: Vec<String> = rel
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect();
    if let Some(last) = segs.pop() {
        let stem = last.trim_end_matches(".rs").to_owned();
        let is_root = segs.is_empty() && (stem == "lib" || stem == "main");
        let is_dir_root = !segs.is_empty() && (stem == "mod" || stem == "main");
        if !is_root && !is_dir_root {
            segs.push(stem);
        }
    }
    segs
}

fn scan_file(
    root: &Path,
    file: &Path,
    pkg: &str,
    prefix: &[String],
    index: &mut TestIndex,
) -> std::io::Result<()> {
    let text = fs::read_to_string(file)?;
    let rel_file = file.strip_prefix(root).unwrap_or(file).to_path_buf();
    for (path, line, ignored) in tests_in_source(&text) {
        let mut parts = vec![pkg.to_owned()];
        parts.extend(prefix.iter().cloned());
        parts.extend(path);
        let id = parts.join("::");
        let t = TestFn {
            id: id.clone(),
            file: rel_file.clone(),
            line,
            ignored,
        };
        if index.tests.insert(id.clone(), t).is_some() {
            index.duplicates.push(id);
        }
    }
    Ok(())
}

#[derive(Debug, Clone, PartialEq)]
enum Tok {
    Ident(String),
    Punct(char),
}

/// Tokens with their line, without comments, strings, chars and lifetimes.
fn tokenize(src: &str) -> Vec<(Tok, usize)> {
    let chars: Vec<char> = src.chars().collect();
    let mut out = Vec::new();
    let mut i = 0;
    let mut line = 1;
    let n = chars.len();
    let bump_lines = |s: &[char]| s.iter().filter(|&&c| c == '\n').count();
    while i < n {
        let c = chars[i];
        if c == '\n' {
            line += 1;
            i += 1;
        } else if c.is_whitespace() {
            i += 1;
        } else if c == '/' && i + 1 < n && chars[i + 1] == '/' {
            while i < n && chars[i] != '\n' {
                i += 1;
            }
        } else if c == '/' && i + 1 < n && chars[i + 1] == '*' {
            let start = i;
            let mut depth = 0;
            while i < n {
                if chars[i] == '/' && i + 1 < n && chars[i + 1] == '*' {
                    depth += 1;
                    i += 2;
                } else if chars[i] == '*' && i + 1 < n && chars[i + 1] == '/' {
                    depth -= 1;
                    i += 2;
                    if depth == 0 {
                        break;
                    }
                } else {
                    i += 1;
                }
            }
            line += bump_lines(&chars[start..i.min(n)]);
        } else if c == '"' || ((c == 'b' || c == 'c') && i + 1 < n && chars[i + 1] == '"') {
            let start = i;
            if c != '"' {
                i += 1;
            }
            i += 1;
            while i < n && chars[i] != '"' {
                if chars[i] == '\\' {
                    i += 1;
                }
                i += 1;
            }
            i += 1;
            line += bump_lines(&chars[start..i.min(n)]);
        } else if (c == 'r' || c == 'b') && raw_string_start(&chars, i).is_some() {
            let (hashes, body) = raw_string_start(&chars, i).unwrap();
            let start = i;
            i = body;
            'raw: while i < n {
                if chars[i] == '"' {
                    let mut k = 0;
                    while k < hashes && i + 1 + k < n && chars[i + 1 + k] == '#' {
                        k += 1;
                    }
                    if k == hashes {
                        i += 1 + hashes;
                        break 'raw;
                    }
                }
                i += 1;
            }
            line += bump_lines(&chars[start..i.min(n)]);
        } else if c == '\'' {
            // Char literal or lifetime.
            if i + 1 < n && chars[i + 1] == '\\' {
                i += 2;
                while i < n && chars[i] != '\'' {
                    i += 1;
                }
                i += 1;
            } else if i + 2 < n && chars[i + 2] == '\'' {
                i += 3;
            } else {
                i += 1;
                while i < n && (chars[i].is_alphanumeric() || chars[i] == '_') {
                    i += 1;
                }
            }
        } else if c.is_alphabetic() || c == '_' {
            let start = i;
            while i < n && (chars[i].is_alphanumeric() || chars[i] == '_') {
                i += 1;
            }
            let word: String = chars[start..i].iter().collect();
            // Raw identifiers r#name.
            out.push((Tok::Ident(word), line));
        } else if c.is_ascii_digit() {
            while i < n && (chars[i].is_alphanumeric() || chars[i] == '_' || chars[i] == '.') {
                i += 1;
            }
        } else {
            out.push((Tok::Punct(c), line));
            i += 1;
        }
    }
    out
}

/// `r"`, `r#"`, `br"`, `br#"` at `i`: returns (hash count, index after the opening quote).
fn raw_string_start(chars: &[char], i: usize) -> Option<(usize, usize)> {
    let mut j = i;
    if chars.get(j) == Some(&'b') {
        j += 1;
    }
    if chars.get(j) != Some(&'r') {
        return None;
    }
    // Must not be part of an identifier (e.g. `bar"`).
    if i > 0 && (chars[i - 1].is_alphanumeric() || chars[i - 1] == '_') {
        return None;
    }
    j += 1;
    let mut hashes = 0;
    while chars.get(j) == Some(&'#') {
        hashes += 1;
        j += 1;
    }
    if chars.get(j) == Some(&'"') {
        Some((hashes, j + 1))
    } else {
        None
    }
}

/// Test functions in one source file: (module path inside the file + fn
/// name, line, ignored).
pub fn tests_in_source(src: &str) -> Vec<(Vec<String>, usize, bool)> {
    let toks = tokenize(src);
    let mut out = Vec::new();
    let mut mods: Vec<(String, usize)> = Vec::new(); // (name, depth inside it)
    let mut depth = 0usize;
    let mut pending_test = false;
    let mut pending_ignore = false;
    let mut pending_mod: Option<String> = None;
    let mut i = 0;
    while i < toks.len() {
        match &toks[i].0 {
            Tok::Punct('#') => {
                // Attribute: #[...] or #![...]
                let mut j = i + 1;
                if matches!(toks.get(j), Some((Tok::Punct('!'), _))) {
                    j += 1;
                }
                if matches!(toks.get(j), Some((Tok::Punct('['), _))) {
                    let start = j + 1;
                    let mut d = 1;
                    j += 1;
                    while j < toks.len() && d > 0 {
                        match toks[j].0 {
                            Tok::Punct('[') => d += 1,
                            Tok::Punct(']') => d -= 1,
                            _ => {}
                        }
                        j += 1;
                    }
                    let attr = &toks[start..j.saturating_sub(1)];
                    // Path part of the attribute: idents and ':' until '(' or '='.
                    let path: Vec<&str> = attr
                        .iter()
                        .take_while(|(t, _)| !matches!(t, Tok::Punct('(') | Tok::Punct('=')))
                        .filter_map(|(t, _)| match t {
                            Tok::Ident(s) => Some(s.as_str()),
                            _ => None,
                        })
                        .collect();
                    if path.last() == Some(&"test") {
                        pending_test = true;
                    }
                    if path == ["ignore"] {
                        pending_ignore = true;
                    }
                    i = j;
                    continue;
                }
                i += 1;
            }
            Tok::Ident(w) if w == "mod" => {
                if let Some((Tok::Ident(name), _)) = toks.get(i + 1) {
                    pending_mod = Some(name.clone());
                    i += 2;
                    continue;
                }
                i += 1;
            }
            Tok::Ident(w) if w == "fn" => {
                if let Some((Tok::Ident(name), _)) = toks.get(i + 1) {
                    if pending_test {
                        let mut path: Vec<String> = mods.iter().map(|(m, _)| m.clone()).collect();
                        path.push(name.clone());
                        out.push((path, toks[i].1, pending_ignore));
                    }
                }
                pending_test = false;
                pending_ignore = false;
                i += 1;
            }
            Tok::Punct('{') => {
                depth += 1;
                if let Some(m) = pending_mod.take() {
                    mods.push((m, depth));
                }
                pending_test = false;
                pending_ignore = false;
                i += 1;
            }
            Tok::Punct('}') => {
                if mods.last().is_some_and(|(_, d)| *d == depth) {
                    mods.pop();
                }
                depth = depth.saturating_sub(1);
                pending_test = false;
                pending_ignore = false;
                pending_mod = None;
                i += 1;
            }
            Tok::Punct(';') => {
                pending_test = false;
                pending_ignore = false;
                pending_mod = None;
                i += 1;
            }
            _ => i += 1,
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_tests_in_nested_modules() {
        let src = r##"
            fn helper() {}
            #[cfg(test)]
            mod tests {
                // #[test] fn commented_out() {}
                const S: &str = "#[test] fn in_string() {}";
                const R: &str = r#"mod fake { #[test] fn raw() {} }"#;
                #[test]
                fn top() { let c = '{'; let l: &'static str = "}"; }
                mod inner {
                    #[test]
                    #[ignore = "slow"]
                    fn deep() {}
                }
                #[tokio::test]
                async fn asynchronous() {}
                #[cfg(test)]
                fn not_a_test() {}
            }
            #[test]
            fn after() {}
        "##;
        let found: Vec<(String, bool)> = tests_in_source(src)
            .into_iter()
            .map(|(p, _, ig)| (p.join("::"), ig))
            .collect();
        assert_eq!(
            found,
            vec![
                ("tests::top".to_owned(), false),
                ("tests::inner::deep".to_owned(), true),
                ("tests::asynchronous".to_owned(), false),
                ("after".to_owned(), false),
            ]
        );
    }

    #[test]
    fn module_segments_follow_cargo_layout() {
        let seg = |p: &str| module_segments(Path::new(p)).join("::");
        assert_eq!(seg("lib.rs"), "");
        assert_eq!(seg("main.rs"), "");
        assert_eq!(seg("mixer.rs"), "mixer");
        assert_eq!(seg("dsp/mod.rs"), "dsp");
        assert_eq!(seg("dsp/eq.rs"), "dsp::eq");
        assert_eq!(seg("render/main.rs"), "render");
    }

    #[test]
    fn discovers_this_crate() {
        let root = crate::workspace_root();
        let index = discover(&root).unwrap();
        assert!(
            index
                .get("od-parity::discover::tests::discovers_this_crate")
                .is_some()
        );
        assert!(index.duplicates.is_empty(), "{:?}", index.duplicates);
    }
}
